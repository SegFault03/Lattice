    @Test void hsqlAndH2PreviewEveryOperationWithoutChangingTheDatabaseThenApplyTheSameStatements() throws Exception {
        for (DatabaseType engine : List.of(DatabaseType.HSQLDB,DatabaseType.H2)) {
            var config = new ConnectionConfig(engine,"alter test"); config.setHsqlMode(HsqlMode.MEM); config.setDatabaseName("alter_"+UUID.randomUUID());
            var manager = new DatabaseConnectionManager();
            try (Connection connection = manager.openConnection(config)) {
                try(var stmt=connection.createStatement()) {
                    stmt.execute("CREATE TABLE \"customers\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"email\" VARCHAR(180), \"amount\" DECIMAL(12,3) DEFAULT 0.000)");
                    stmt.execute("INSERT INTO \"customers\" (\"email\",\"amount\") VALUES ('ada@example.com',1.234)");
                }
                List<String> executed = new ArrayList<>(); Connection recording = record(connection,executed);
                ColumnMetadata email = column(connection,config,"customers","email");
                var modify = TableAlteration.column(TableAlteration.Kind.MODIFY,email,"email",email.getTypeName(),"255",true,"");
                List<String> sql=DdlService.getInstance().previewAlter(recording,config,"PUBLIC","customers",modify);
                assertTrue(executed.isEmpty(),"Preview must only read metadata"); assertEquals(180,column(connection,config,"customers","email").getColumnSize());
                DdlService.getInstance().applyAlter(recording,config,"PUBLIC","customers",modify);
                assertEquals(sql,executed); assertEquals(255,column(connection,config,"customers","email").getColumnSize());
                assertTrue(column(connection,config,"customers","id").isAutoIncrement());

                var add=TableAlteration.column(TableAlteration.Kind.ADD,null,"loyalty","DECIMAL","10, 2",false,"0");
                applyAndCompare(recording,config,"customers",add,executed);
                assertEquals(2,column(connection,config,"customers","loyalty").getDecimalDigits());
                var rename=TableAlteration.column(TableAlteration.Kind.RENAME_COLUMN,column(connection,config,"customers","email"),"email_address","","",true,"");
                applyAndCompare(recording,config,"customers",rename,executed);
                assertEquals(255,column(connection,config,"customers","email_address").getColumnSize());
                var drop=TableAlteration.column(TableAlteration.Kind.DROP,column(connection,config,"customers","loyalty"),"loyalty","","",false,"");
                applyAndCompare(recording,config,"customers",drop,executed);
                assertEquals(3,MetadataService.getInstance().getColumns(connection,config,"PUBLIC","customers").size());
                var renameTable=TableAlteration.column(TableAlteration.Kind.RENAME_TABLE,null,"contacts","","",false,"");
                applyAndCompare(recording,config,"customers",renameTable,executed);
                assertEquals(3,MetadataService.getInstance().getColumns(connection,config,"PUBLIC","contacts").size());
                try(var stmt=connection.createStatement();var rows=stmt.executeQuery("SELECT \"email_address\",\"amount\" FROM \"contacts\"")) {
                    assertTrue(rows.next());assertEquals("ada@example.com",rows.getString(1));assertEquals("1.234",rows.getBigDecimal(2).toPlainString());
                }
            } finally { manager.dispose(); }
        }
    }
    @Test void unchangedDefaultExpressionsAndDecimalScaleSurviveModification() throws Exception {
        for(DatabaseType engine:List.of(DatabaseType.HSQLDB,DatabaseType.H2)) {
            var config=new ConnectionConfig(engine,"defaults");config.setHsqlMode(HsqlMode.MEM);config.setDatabaseName("defaults_"+UUID.randomUUID());
            var manager=new DatabaseConnectionManager();
            try(var conn=manager.openConnection(config);var statement=conn.createStatement()) {
                statement.execute("CREATE TABLE \"items\" (\"value\" DECIMAL(12,3) DEFAULT 3.234, \"created\" TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP)");
                var original=column(conn,config,"items","value");
                var edit=TableAlteration.column(TableAlteration.Kind.MODIFY,original,"value",original.getTypeName(),"15, 3",false,original.getDefaultValue());
                var preview=DdlService.getInstance().previewAlter(conn,config,"PUBLIC","items",edit);
                assertFalse(preview.isEmpty()); DdlService.getInstance().applyAlter(conn,config,"PUBLIC","items",edit);
                var created = column(conn,config,"items","created");
                var timestamp = TableAlteration.column(TableAlteration.Kind.MODIFY,created,"created",created.getTypeName(),"",false,created.getDefaultValue());
                DdlService.getInstance().applyAlter(conn,config,"PUBLIC","items",timestamp);
                statement.execute("INSERT INTO \"items\" DEFAULT VALUES");
                try(var row=statement.executeQuery("SELECT \"value\",\"created\" FROM \"items\"")) {assertTrue(row.next());assertEquals("3.234",row.getBigDecimal(1).toPlainString());assertNotNull(row.getTimestamp(2));}
                assertEquals(3,column(conn,config,"items","value").getDecimalDigits());
                assertEquals(3,column(conn,config,"items","created").getDecimalDigits());
            } finally {manager.dispose();}
        }
    }
    @Test void externalSchemaChangesCannotBeOverwrittenByAnOldEditorSnapshot() throws Exception {
        var config = new ConnectionConfig(DatabaseType.H2,"stale"); config.setHsqlMode(HsqlMode.MEM); config.setDatabaseName("stale_"+UUID.randomUUID());
        var manager = new DatabaseConnectionManager();
        try(var conn=manager.openConnection(config);var statement=conn.createStatement()) {
            statement.execute("CREATE TABLE \"items\" (\"email\" VARCHAR(180))");
            var original=column(conn,config,"items","email");
            var edit=TableAlteration.column(TableAlteration.Kind.MODIFY,original,"email",original.getTypeName(),"255",true,"");
            DdlService.getInstance().previewAlter(conn,config,"PUBLIC","items",edit);
            statement.execute("ALTER TABLE \"items\" ALTER COLUMN \"email\" VARCHAR(200)");
            assertTrue(assertThrows(SQLException.class,()->DdlService.getInstance().applyAlter(conn,config,"PUBLIC","items",edit)).getMessage().contains("changed"));
            assertEquals(200,column(conn,config,"items","email").getColumnSize());
        } finally {manager.dispose();}
    }
    @Test void aMixedBatchModifiesAndRenamesTheSameColumnAddsMultipleColumnsAndRenamesTheTable() throws Exception {
        for(DatabaseType engine:List.of(DatabaseType.HSQLDB,DatabaseType.H2)) {
            var config=new ConnectionConfig(engine,"batch"); config.setHsqlMode(HsqlMode.MEM);config.setDatabaseName("batch_"+UUID.randomUUID());
            var manager=new DatabaseConnectionManager();
            try(var conn=manager.openConnection(config);var statement=conn.createStatement()) {
                statement.execute("CREATE TABLE \"customers\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"email\" VARCHAR(180), \"obsolete\" INT)");
                statement.execute("INSERT INTO \"customers\" (\"email\") VALUES ('ada@example.com')");
                var baseline=MetadataService.getInstance().getColumns(conn,config,"PUBLIC","customers");
                var email=column(conn,config,"customers","email");
                var drop=new TableAlteration(TableAlteration.Kind.DROP,column(conn,config,"customers","obsolete"),"obsolete","",0,0,false,"");
                var modify=TableAlteration.column(TableAlteration.Kind.MODIFY,email,"email","VARCHAR","255",false,"");
                var rename=new TableAlteration(TableAlteration.Kind.RENAME_COLUMN,email,"email_address","",0,0,false,"");
                var add=TableAlteration.column(TableAlteration.Kind.ADD,null,"loyalty","DECIMAL","10, 2",true,"0");
                var second=TableAlteration.column(TableAlteration.Kind.ADD,null,"nickname","VARCHAR","32",true,"");
                var table=new TableAlteration(TableAlteration.Kind.RENAME_TABLE,null,"contacts","",0,0,false,"");
                var batch=new TableAlterationBatch("customers",baseline,List.of(table,rename,add,modify,second,drop));
                var executed=new ArrayList<String>();var recording=record(conn,executed);
                var sql=DdlService.getInstance().previewAlterBatch(recording,config,"PUBLIC",batch);
                assertTrue(executed.isEmpty());assertEquals(180,column(conn,config,"customers","email").getColumnSize());
                DdlService.getInstance().applyAlterBatch(recording,config,"PUBLIC",batch,sql); assertEquals(sql,executed);
                var columns=MetadataService.getInstance().getColumns(conn,config,"PUBLIC","contacts");
                assertEquals(List.of("id","email_address","loyalty","nickname"),columns.stream().map(ColumnMetadata::getName).toList());
                assertEquals(255,column(conn,config,"contacts","email_address").getColumnSize());
                assertEquals(2,column(conn,config,"contacts","loyalty").getDecimalDigits());
                assertTrue(column(conn,config,"contacts","id").isAutoIncrement());
                try(var rows=statement.executeQuery("SELECT \"email_address\" FROM \"contacts\"")) {assertTrue(rows.next());assertEquals("ada@example.com",rows.getString(1));}
            } finally {manager.dispose();}
        }
    }
    @Test void batchFailureReportsCommittedStepsAndStopsBeforeLaterOperations() throws Exception {
        for(DatabaseType engine:List.of(DatabaseType.HSQLDB,DatabaseType.H2)) {
            var config=new ConnectionConfig(engine,"partial batch"); config.setHsqlMode(HsqlMode.MEM);config.setDatabaseName("partial_"+UUID.randomUUID());
            var manager=new DatabaseConnectionManager();
            try(var conn=manager.openConnection(config);var statement=conn.createStatement()) {
                statement.execute("CREATE TABLE \"customers\" (\"email\" VARCHAR(180))");
                var baseline=MetadataService.getInstance().getColumns(conn,config,"PUBLIC","customers");var email=baseline.getFirst();
                var modify=TableAlteration.column(TableAlteration.Kind.MODIFY,email,"email","VARCHAR","255",true,"");
                var rename=new TableAlteration(TableAlteration.Kind.RENAME_COLUMN,email,"email_address","",0,0,false,"");
                var first=TableAlteration.column(TableAlteration.Kind.ADD,null,"loyalty","VARCHAR","32",true,"");
                var bad=TableAlteration.column(TableAlteration.Kind.ADD,null,"nickname","VARCHAR","32",true,"SQL:NO_SUCH_FUNCTION()");
                var later=TableAlteration.column(TableAlteration.Kind.ADD,null,"later","VARCHAR","32",true,"");
                var batch=new TableAlterationBatch("customers",baseline,List.of(modify,rename,first,bad,later));
                var sql=DdlService.getInstance().previewAlterBatch(conn,config,"PUBLIC",batch);
                var failure=assertThrows(DdlService.BatchFailure.class,()->DdlService.getInstance().applyAlterBatch(conn,config,"PUBLIC",batch,sql));
                assertEquals(List.of(modify,rename,first),failure.completed());
                assertEquals(List.of("email_address","loyalty"),MetadataService.getInstance().getColumns(conn,config,"PUBLIC","customers").stream().map(ColumnMetadata::getName).toList());
                assertEquals(255,column(conn,config,"customers","email_address").getColumnSize());
            } finally {manager.dispose();}
        }
    }
    @Test void batchPreflightChecksEveryColumnAndReviewedSqlBeforeAnyWrite() throws Exception {
        var config=new ConnectionConfig(DatabaseType.H2,"stale batch");config.setDatabaseName("stale_batch_"+UUID.randomUUID());var manager=new DatabaseConnectionManager();
        try(var conn=manager.openConnection(config);var statement=conn.createStatement()) {
            statement.execute("CREATE TABLE \"customers\" (\"email\" VARCHAR(180),\"other\" VARCHAR(32))");
            var baseline=MetadataService.getInstance().getColumns(conn,config,"PUBLIC","customers");
            var add=TableAlteration.column(TableAlteration.Kind.ADD,null,"loyalty","VARCHAR","32",true,"");
            var batch=new TableAlterationBatch("customers",baseline,List.of(add));var executed=new ArrayList<String>();var recording=record(conn,executed);
            var sql=DdlService.getInstance().previewAlterBatch(recording,config,"PUBLIC",batch);
            assertThrows(SQLException.class,()->DdlService.getInstance().applyAlterBatch(recording,config,"PUBLIC",batch,List.of("wrong SQL")));assertTrue(executed.isEmpty());
            statement.execute("ALTER TABLE \"customers\" ALTER COLUMN \"other\" VARCHAR(64)");
            assertThrows(SQLException.class,()->DdlService.getInstance().applyAlterBatch(recording,config,"PUBLIC",batch,sql));assertTrue(executed.isEmpty());
            assertEquals(2,MetadataService.getInstance().getColumns(conn,config,"PUBLIC","customers").size());
        } finally {manager.dispose();}
    }
    private static ColumnMetadata column(Connection conn,ConnectionConfig config,String table,String name) throws Exception {
        return MetadataService.getInstance().getColumns(conn,config,"PUBLIC",table).stream().filter(c->c.getName().equals(name)).findFirst().orElseThrow();
    }
    private static void applyAndCompare(Connection conn,ConnectionConfig config,String table,TableAlteration edit,List<String> executed) throws Exception {
        executed.clear();var sql=DdlService.getInstance().previewAlter(conn,config,"PUBLIC",table,edit);
        assertTrue(executed.isEmpty());DdlService.getInstance().applyAlter(conn,config,"PUBLIC",table,edit);assertEquals(sql,executed);
    }
    private static Connection record(Connection delegate,List<String> executed) {
        return (Connection)Proxy.newProxyInstance(Connection.class.getClassLoader(),new Class[]{Connection.class},(p,m,a)->{
            Object result=invoke(delegate,m,a);
            if(m.getName().equals("createStatement"))return Proxy.newProxyInstance(Statement.class.getClassLoader(),new Class[]{Statement.class},(sp,sm,sa)->{
                if(sm.getName().equals("execute") && ((String)sa[0]).startsWith("ALTER TABLE")) executed.add((String)sa[0]);
                return invoke(result,sm,sa);
            });
            return result;
        });
    }
    private static Object invoke(Object target,Method method,Object[] args)throws Throwable {
        try{return method.invoke(target,args);}catch(InvocationTargetException failure){throw failure.getCause();}
    }
