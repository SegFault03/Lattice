package com.segfault03.ideadb.service;

import com.intellij.util.xmlb.XmlSerializer;
import com.segfault03.ideadb.model.*;
import com.segfault03.ideadb.state.MetadataCacheState;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class MetadataCacheTest {
    @Test void hsqlMetadataSurvivesDisconnectAndXmlReload() throws Exception { verifyOfflineCache(DatabaseType.HSQLDB); }
    @Test void h2MetadataSurvivesDisconnectAndXmlReload() throws Exception { verifyOfflineCache(DatabaseType.H2); }

    private void verifyOfflineCache(DatabaseType type) throws Exception {
        var config = new ConnectionConfig(type, "Cached source");
        config.setHsqlMode(HsqlMode.MEM);
        config.setDatabaseName("metadata_cache_" + System.nanoTime());
        var manager = new DatabaseConnectionManager();
        var cache = MetadataCacheState.getInstance();
        var service = MetadataService.getInstance();
        try {
            var connection = manager.getConnection(config);
            try (var statement = connection.createStatement()) {
                statement.execute("CREATE TABLE PUBLIC.PARENT (ID INTEGER PRIMARY KEY)");
                statement.execute("CREATE TABLE PUBLIC.CHILD (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, PARENT_ID INTEGER REFERENCES PUBLIC.PARENT(ID), LABEL VARCHAR(40) DEFAULT 'new')");
                statement.execute("CREATE VIEW PUBLIC.CHILD_VIEW AS SELECT ID FROM PUBLIC.CHILD");
            }
            service.getDatabases(connection, config);
            service.getTables(connection, config, "PUBLIC");
            var columns = service.getColumns(connection, config, "PUBLIC", "CHILD");
            manager.closeConnection(config.getId());
            assertThrows(Exception.class, () -> service.getDatabases(connection, config));
            assertThrows(Exception.class, () -> service.getTables(connection, config, "PUBLIC"));
            assertThrows(Exception.class, () -> service.getColumns(connection, config, "PUBLIC", "CHILD"));

            var persisted = XmlSerializer.serialize(cache.getState());
            var restored = new MetadataCacheState();
            restored.loadState(XmlSerializer.deserialize(persisted, MetadataCacheState.State.class));
            var namespace = restored.snapshot(config).namespaces().stream().filter(n -> n.name().equals("PUBLIC")).findFirst().orElseThrow();
            assertTrue(namespace.tablesLoaded());
            assertTrue(namespace.tables().stream().anyMatch(t -> t.metadata().isView() && t.metadata().getName().equals("CHILD_VIEW")));
            var child = namespace.tables().stream().filter(t -> t.metadata().getName().equals("CHILD")).findFirst().orElseThrow();
            assertTrue(child.columnsLoaded());
            assertEquals(columns.stream().map(ColumnMetadata::toString).toList(), child.columns().stream().map(ColumnMetadata::toString).toList());
            assertTrue(child.columns().stream().anyMatch(c -> c.getName().equals("ID") && c.isPrimaryKey() && c.isAutoIncrement()));
            assertTrue(child.columns().stream().anyMatch(c -> c.getName().equals("PARENT_ID") && c.isForeignKey()));
            assertEquals(List.of("ID"), child.metadata().getPrimaryKeyColumnNames());
        } finally {
            manager.dispose();
            cache.remove(config.getId());
        }
    }

    @Test void refreshPrunesRemovedObjectsAndReplacesColumnsWithoutLosingUnrefreshedKeys() {
        var cache = new MetadataCacheState();
        var config = new ConnectionConfig(DatabaseType.HSQLDB, "Cache");
        cache.databasesRefreshed(config, List.of("PUBLIC", "REMOVED"));
        var table = new TableMetadata(null, "PUBLIC", "CHILD", "TABLE");
        cache.tablesRefreshed(config, "PUBLIC", List.of(table, new TableMetadata(null, "PUBLIC", "DROPPED", "TABLE")));
        cache.columnsRefreshed(config, "PUBLIC", "CHILD", List.of(new ColumnMetadata("ID", "INTEGER", java.sql.Types.INTEGER, 10, 0, false, true, true, null)));
        cache.databasesRefreshed(config, List.of("PUBLIC"));
        cache.tablesRefreshed(config, "PUBLIC", List.of(table));
        var snapshot = cache.snapshot(config);
        assertEquals(1, snapshot.namespaces().size());
        assertEquals(1, snapshot.namespaces().getFirst().tables().size());
        assertEquals(List.of("ID"), snapshot.namespaces().getFirst().tables().getFirst().metadata().getPrimaryKeyColumnNames());
        cache.columnsRefreshed(config, "PUBLIC", "CHILD", List.of());
        assertTrue(cache.snapshot(config).namespaces().getFirst().tables().getFirst().columns().isEmpty());
        assertTrue(cache.snapshot(config).namespaces().getFirst().tables().getFirst().columnsLoaded());
        cache.tablesRefreshed(config, "PUBLIC", List.of());
        assertTrue(cache.snapshot(config).namespaces().getFirst().tables().isEmpty());
        assertTrue(cache.snapshot(config).namespaces().getFirst().tablesLoaded());
    }

    @Test void sourcesAreIsolatedAndChangedEndpointsCannotReuseOldMetadataOrExposeCredentials() {
        var cache = new MetadataCacheState();
        var config = new ConnectionConfig(DatabaseType.MYSQL, "Cache");
        config.setCustomUrl("jdbc:mysql://db:3306/demo?user=secret_user&password=secret_url_password");
        config.setPassword("secret_password");
        cache.databasesRefreshed(config, List.of("demo"));
        String xml = new org.jdom.output.XMLOutputter().outputString(XmlSerializer.serialize(cache.getState()));
        assertFalse(xml.contains("secret_user"));
        assertFalse(xml.contains("secret_password"));
        assertFalse(xml.contains("secret_url_password"));
        var another = config.copy(); another.setId("another");
        assertNull(cache.snapshot(another));
        var changed = config.copy(); changed.setCustomUrl("jdbc:mysql://other:3306/demo");
        assertNull(cache.snapshot(changed));
        changed = config.copy(); changed.setUser("another_user");
        assertNull(cache.snapshot(changed));
        var renamed = config.copy(); renamed.setName("Renamed source");
        assertNotNull(cache.snapshot(renamed));
        cache.remove(config.getId());
        assertNull(cache.snapshot(config));
    }

    @Test void callersCannotMutateTheCacheThroughSnapshotsOrPersistenceState() {
        var cache = new MetadataCacheState();
        var config = new ConnectionConfig(DatabaseType.MYSQL, "Cache");
        cache.databasesRefreshed(config, List.of("demo"));
        cache.tablesRefreshed(config, "demo", List.of(new TableMetadata("demo", null, "items", "TABLE")));
        cache.snapshot(config).namespaces().getFirst().tables().getFirst().metadata().addColumn(
                new ColumnMetadata("injected", "INTEGER", java.sql.Types.INTEGER, 10, 0, true, false, false, null));
        cache.getState().sources.clear();
        assertTrue(cache.snapshot(config).namespaces().getFirst().tables().getFirst().metadata().getColumns().isEmpty());
    }

    @Test void revisionsArePerConnectionAndInvalidatedColumnsAreNoLongerTrusted() {
        var cache = new MetadataCacheState();
        var first = new ConnectionConfig(DatabaseType.HSQLDB, "First");
        var second = new ConnectionConfig(DatabaseType.HSQLDB, "Second");
        cache.tablesRefreshed(first, "PUBLIC", List.of(new TableMetadata(null, "PUBLIC", "T", "TABLE")));
        cache.columnsRefreshed(first, "PUBLIC", "T", List.of());
        long before = cache.revision(first.getId());

        cache.tablesRefreshed(second, "PUBLIC", List.of());
        assertEquals(before, cache.revision(first.getId()), "A change to another connection is not a change to this one");
        assertTrue(cache.revision(second.getId()) > 0);

        cache.columnsInvalidated(first, "PUBLIC", List.of("T"));
        assertTrue(cache.revision(first.getId()) > before);
        assertFalse(cache.snapshot(first).namespaces().getFirst().tables().getFirst().columnsLoaded());
    }
}
