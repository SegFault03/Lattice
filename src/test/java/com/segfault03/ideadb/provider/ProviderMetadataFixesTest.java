package com.segfault03.ideadb.provider;

import com.segfault03.ideadb.model.*;
import com.segfault03.ideadb.service.DatabaseConnectionManager;
import org.junit.jupiter.api.Test;
import java.sql.*;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

@org.junit.jupiter.api.Tag("functional")
class ProviderMetadataFixesTest {
    private static ConnectionConfig embedded(DatabaseType type) {
        var config = new ConnectionConfig(type, "embedded");
        if (type == DatabaseType.H2) config.setDatabaseName("fixes_" + UUID.randomUUID());
        else config.setCustomUrl("jdbc:hsqldb:mem:fixes_" + UUID.randomUUID() + ";shutdown=true");
        return config;
    }

    @Test void mysqlUrlRequestsOpportunisticTlsInsteadOfDisablingIt() {
        String url = DatabaseProviders.get(DatabaseType.MYSQL).buildJdbcUrl(new ConnectionConfig(DatabaseType.MYSQL, "tls"));
        assertTrue(url.contains("sslMode=PREFERRED") && url.contains("allowPublicKeyRetrieval=true") && url.contains("connectTimeout=10000"));
        assertFalse(url.contains("useSSL"));
    }

    @Test void hsqlAndH2OfferOnlyTypesTheEngineAccepts() throws Exception {
        for (var type : List.of(DatabaseType.H2, DatabaseType.HSQLDB)) {
            var provider = DatabaseProviders.get(type);
            var config = embedded(type);
            try (Connection c = new DatabaseConnectionManager().getConnection(config)) {
                for (String dt : provider.dataTypes()) {
                    var column = new ColumnDefinition("C", dt, dt.contains("CHAR") || dt.contains("BINARY") ? 10 : 0, true, false, false, "");
                    String sql = provider.dialect().buildCreateTableSql(config, null, "T_" + Math.abs(dt.hashCode()), List.of(column));
                    try (Statement s = c.createStatement()) { s.execute(sql); }
                    catch (SQLException failure) { fail(type + " rejects " + dt + ": " + failure.getMessage()); }
                }
            }
        }
        assertFalse(DatabaseProviders.get(DatabaseType.HSQLDB).dataTypes().contains("TEXT"));
        assertTrue(DatabaseProviders.get(DatabaseType.MYSQL).dataTypes().containsAll(List.of("TINYINT", "DATETIME", "LONGTEXT", "JSON", "VARBINARY", "LONGBLOB")));
    }

    @Test void generatedColumnsAreGeneratedNotAutoIncrementWhileIdentityStaysAutoIncrement() throws Exception {
        for (var type : List.of(DatabaseType.H2, DatabaseType.HSQLDB)) {
            var config = embedded(type);
            try (Connection c = new DatabaseConnectionManager().getConnection(config); Statement s = c.createStatement()) {
                s.execute("CREATE TABLE \"Mixed_Case\" (ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, A INT, B INT GENERATED ALWAYS AS (A + 1))");
                var provider = DatabaseProviders.get(type);
                String schema = provider.metadata().currentSchema(c);
                var columns = new HashMap<String, ColumnMetadata>();
                // Exact, lower-cased and unquoted spellings all resolve to the same table.
                for (var column : provider.metadata().getColumns(c, config, schema, "Mixed_Case")) columns.put(column.getName(), column);
                assertTrue(columns.get("ID").isAutoIncrement() && !columns.get("ID").isGenerated(), type.toString());
                assertTrue(columns.get("B").isGenerated() && !columns.get("B").isAutoIncrement(), type.toString());
                assertFalse(columns.get("A").isGenerated() || columns.get("A").isAutoIncrement());
                s.execute("CREATE TABLE PLAIN (X INT)");
                assertEquals(1, provider.metadata().getColumns(c, config, schema, "plain").size());
            }
        }
    }

    @Test void autoDefaultsAreUnquotedOnlyForMatchingColumnTypes() {
        var config = new ConnectionConfig(DatabaseType.H2, "defaults");
        var dialect = new H2Dialect();
        java.util.function.BiFunction<String, String, String> add = (type, value) ->
                dialect.buildAddColumnSql(config, "PUBLIC", "T", new ColumnDefinition("C", type, 0, true, false, false, value));
        assertTrue(add.apply("INT", "42").endsWith("DEFAULT 42;"));
        assertTrue(add.apply("DECIMAL(10,2)", "-1.5").endsWith("DEFAULT -1.5;"));
        assertTrue(add.apply("BOOLEAN", "true").endsWith("DEFAULT true;"));
        assertTrue(add.apply("VARCHAR", "42").endsWith("DEFAULT '42';"));
        assertTrue(add.apply("VARCHAR", "TRUE").endsWith("DEFAULT 'TRUE';"));
        assertTrue(add.apply("TINYINT(1)", "TRUE").endsWith("DEFAULT TRUE;"), "MySQL booleans are TINYINT(1)");
        assertTrue(add.apply("VARCHAR", "NULL").endsWith("DEFAULT NULL;"));
        assertTrue(add.apply("VARCHAR", "'it''s'").endsWith("DEFAULT 'it''s';"));
        assertTrue(add.apply("VARCHAR", "'").endsWith("DEFAULT '''';"));
        assertTrue(add.apply("VARCHAR", "''").endsWith("DEFAULT '';"));
    }
}
