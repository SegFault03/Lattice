package com.segfault03.ideadb.provider;

import com.segfault03.ideadb.model.*;
import com.segfault03.ideadb.service.*;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.file.Path;
import java.sql.*;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

@org.junit.jupiter.api.Tag("functional")
class H2FeatureTest {
    @TempDir Path temporary;

    @Test void fileDatabaseSurvivesLastConnectionClosing() throws Exception {
        var config = new ConnectionConfig(DatabaseType.H2, "file");
        config.setHsqlMode(HsqlMode.FILE);
        config.setDatabaseName(temporary.resolve("persistent").toString());
        var manager = new DatabaseConnectionManager();
        try {
            try (var conn = manager.openConnection(config); var stmt = conn.createStatement()) {
                stmt.execute("CREATE TABLE ITEMS(ID INT PRIMARY KEY)");
                stmt.execute("INSERT INTO ITEMS VALUES(7)");
            }
            try (var conn = manager.openConnection(config); var stmt = conn.createStatement(); var rows = stmt.executeQuery("SELECT ID FROM ITEMS")) {
                assertTrue(rows.next()); assertEquals(7, rows.getInt(1));
            }
        } finally { manager.dispose(); }
    }

    @Test void generatedColumnsIdentityPrecisionAndNativeDdlArePreserved() throws Exception {
        var config = new ConnectionConfig(DatabaseType.H2, "metadata");
        config.setDatabaseName("metadata_" + UUID.randomUUID());
        var manager = new DatabaseConnectionManager();
        var provider = DatabaseProviders.get(DatabaseType.H2);
        try (var conn = manager.openConnection(config); var stmt = conn.createStatement()) {
            stmt.execute("CREATE SCHEMA \"odd_%schema\"");
            stmt.execute("CREATE TABLE \"odd_%schema\".\"items_%\" (ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, AMOUNT DECIMAL(12,3), DOUBLED DECIMAL(12,3) GENERATED ALWAYS AS (AMOUNT*2), AT_TIME TIMESTAMP(3), UNIQUE(AMOUNT))");
            var columns = provider.metadata().getColumns(conn, config, "odd_%schema", "items_%");
            assertEquals(4, columns.size());
            assertTrue(columns.get(0).isAutoIncrement());
            assertFalse(columns.get(0).isGenerated());
            assertEquals(3, columns.get(1).getDecimalDigits());
            assertTrue(columns.get(2).isGenerated());
            assertEquals(3, columns.get(3).getDecimalDigits());
            var table = provider.metadata().getTables(conn, config, "odd_%schema").getFirst();
            String ddl = provider.dialect().getCreateTableStatement(conn, config, "odd_%schema", table);
            assertTrue(ddl.contains("GENERATED ALWAYS AS"), ddl);
            assertTrue(ddl.contains("UNIQUE"), ddl);
            stmt.execute("DROP TABLE \"odd_%schema\".\"items_%\"");
            for (String sql : ddl.split(";")) if (!sql.isBlank()) stmt.execute(sql);
            assertEquals(4, provider.metadata().getColumns(conn, config, "odd_%schema", "items_%").size());
        } finally { manager.dispose(); }
    }

    @Test void explicitJarUsesAnIsolatedDriverAndCleansUpRegistrations() throws Exception {
        Path jar;
        try (var jars = java.nio.file.Files.list(Path.of(System.getProperty("lattice.test.drivers", "build/fallback-drivers")))) {
            jar = jars.filter(path -> path.getFileName().toString().startsWith("h2-")).findFirst().orElseThrow();
        }
        var config = new ConnectionConfig(DatabaseType.H2, "isolated");
        config.setDriverSource(DriverSource.LOCAL_JAR); config.setDriverJarPath(jar.toString());
        var registry = new DriverRegistry();
        Class<?> cleanup; ClassLoader owner;
        try {
            var driver = registry.getDriver(config);
            owner = driver.getClass().getClassLoader();
            assertNotSame(org.h2.Driver.class.getClassLoader(), owner);
            assertSame(driver, registry.getDriver(config));
            cleanup = Class.forName(JdbcDriverCleanup.class.getName(), true, owner);
            var props = new Properties(); props.setProperty("user", "sa");
            try (var conn = driver.connect(config.buildJdbcUrl(), props)) { assertFalse(conn.isClosed()); }
        } finally { registry.dispose(); }
        assertEquals(0, ((Number) cleanup.getMethod("registeredCount", ClassLoader.class).invoke(null, owner)).intValue());
    }
}
